    market             text PRIMARY KEY,
    last_source_marker text,
    last_scraped_at    timestamp NOT NULL DEFAULT now(),
    products_count     integer
);

-- ---------------------------------------------------------------------------
-- API-facing materialized read models (refreshed CONCURRENTLY by pipeline/scrapers)
-- ---------------------------------------------------------------------------
CREATE MATERIALIZED VIEW IF NOT EXISTS public.grouped_products AS
SELECT g.id AS group_id,
       g.name AS group_name,
       g.main_category,
       g.sub_category,
       g.manufacturer_id,
       array_agg(DISTINCT p.market) AS markets,
       count(DISTINCT p.market)::int AS market_count,
       min(p.price) AS min_price,
       bool_or(p.regular_price IS NOT NULL) AS on_sale,
       COALESCE(
           array_agg(DISTINCT p.market) FILTER (WHERE p.regular_price IS NOT NULL),
           '{}'::text[]
       ) AS sale_markets,
       max(
           CASE
               WHEN p.regular_price IS NOT NULL AND p.price IS NOT NULL AND p.regular_price > p.price
               THEN GREATEST(1, LEAST(99, round((1.0 - p.price::numeric / p.regular_price) * 100)::int))
           END
       ) AS max_discount_pct,
       max(
           CASE
               WHEN p.regular_price IS NOT NULL AND p.price IS NOT NULL AND p.regular_price > p.price
               THEN (p.regular_price - p.price)
           END
       ) AS max_discount_amount,
       json_agg(json_build_object(
           'product_id', p.id,
           'name', p.name,
           'price', p.price,
           'regular_price', p.regular_price,
           'market', p.market,
           'in_stock', p.in_stock,
           'image', p.image,
           'link', p.link,
           'singular_price', p.singular_price
       ) ORDER BY p.price) AS products
FROM public.groups g
JOIN public.products p ON p.group_id = g.id
WHERE p.in_stock = true
GROUP BY g.id
WITH DATA;

-- Unique index enables REFRESH MATERIALIZED VIEW CONCURRENTLY and /search PK joins
CREATE UNIQUE INDEX IF NOT EXISTS idx_grouped_products_group_id
    ON public.grouped_products USING btree (group_id);

-- /manufacturer hot path: pure ordered range scan, zero join, zero sort;
-- INCLUDE keeps subcategory/market/sale-filtered scans index-only until LIMIT
CREATE INDEX IF NOT EXISTS idx_grouped_products_manufacturer_name
    ON public.grouped_products USING btree (manufacturer_id, group_name)
    INCLUDE (main_category, sub_category, markets, on_sale, sale_markets)
    WHERE manufacturer_id IS NOT NULL;

-- /{main}/{sub} hot path: covering index with INCLUDE for index-only counts
-- and market/sale-filtered page slices without JSON deserialization
CREATE INDEX IF NOT EXISTS idx_grouped_products_category_name
    ON public.grouped_products USING btree (main_category, sub_category, group_name)
    INCLUDE (markets, on_sale, sale_markets);

-- O(1) manufacturer header stats (groups, categories, markets, subcategories)
CREATE MATERIALIZED VIEW IF NOT EXISTS public.manufacturer_stats AS
WITH visible_groups AS (
    SELECT g.id, g.manufacturer_id, g.main_category, g.sub_category
    FROM public.groups g
    WHERE g.manufacturer_id IS NOT NULL
      AND EXISTS (
          SELECT 1
          FROM public.products p
          WHERE p.group_id = g.id AND p.in_stock = true
      )
),
sub_counts AS (
    SELECT manufacturer_id,
           main_category,
           sub_category,
           count(*)::int AS count
    FROM visible_groups
    GROUP BY manufacturer_id, main_category, sub_category
),
base_counts AS (
    SELECT manufacturer_id,
           sum(count)::int AS groups,
           count(DISTINCT main_category)::int AS categories
    FROM sub_counts
    GROUP BY manufacturer_id
),
sub_agg AS (
    SELECT manufacturer_id,
           jsonb_agg(
               jsonb_build_object(
                   'main_category', main_category,
                   'sub_category', sub_category,
                   'count', count
               )
               ORDER BY count DESC, sub_category ASC
           ) AS subcategories
    FROM sub_counts
    WHERE main_category IS NOT NULL AND sub_category IS NOT NULL
    GROUP BY manufacturer_id
),
market_counts AS (
    SELECT g.manufacturer_id,
           count(DISTINCT p.market)::int AS markets,
           max(p.last_updated) AS last_updated
    FROM public.groups g
    JOIN public.products p ON p.group_id = g.id
    WHERE g.manufacturer_id IS NOT NULL
      AND p.in_stock = true
    GROUP BY g.manufacturer_id
)
SELECT b.manufacturer_id,
       b.groups,
       b.categories,
       COALESCE(mc.markets, 0)::int AS markets,
       mc.last_updated,
       COALESCE(sa.subcategories, '[]'::jsonb) AS subcategories
FROM base_counts b
LEFT JOIN sub_agg sa ON sa.manufacturer_id = b.manufacturer_id
LEFT JOIN market_counts mc ON mc.manufacturer_id = b.manufacturer_id
WITH DATA;

CREATE UNIQUE INDEX IF NOT EXISTS idx_manufacturer_stats_manufacturer_id
    ON public.manufacturer_stats USING btree (manufacturer_id);

