-- CenaPlus — complete database schema (single source of truth).
--
-- Bootstraps an empty database to the current production shape: extensions,
-- tables, constraints, indexes, the timestamp trigger and the grouped_products
-- view. Mounted into /docker-entrypoint-initdb.d, so `docker compose up` on a
-- fresh volume creates everything automatically.
--
-- Recover after dropping the database:
--   createdb products_db && psql -d products_db -f init/00_schema.sql
-- (or simply recreate the volume and let the entrypoint run it)
--
-- This file is a fresh-database bootstrap. It uses IF NOT EXISTS where cheap,
-- but it does not migrate an existing database — schema changes to a live
-- database are applied with the matching statements and then folded back here.

CREATE EXTENSION IF NOT EXISTS "uuid-ossp" WITH SCHEMA public;
COMMENT ON EXTENSION "uuid-ossp" IS 'generate universally unique identifiers (UUIDs)';

CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;
COMMENT ON EXTENSION vector IS 'vector data type and ivfflat and hnsw access methods';

CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;
COMMENT ON EXTENSION pg_trgm IS 'text similarity measurement and index searching based on trigrams';

-- ---------------------------------------------------------------------------
-- Manufacturer registry (canonical names + alias cross-references)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.manufacturers (
    id             bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    canonical_name text   NOT NULL,
    display_name   text,
    created_at     timestamptz NOT NULL DEFAULT now(),
    -- set when this row was absorbed by another manufacturer; rows are never deleted
    merged_into    bigint,
    CONSTRAINT manufacturers_pkey PRIMARY KEY (id),
    CONSTRAINT manufacturers_canonical_name_key UNIQUE (canonical_name),
    CONSTRAINT manufacturers_merged_into_fkey
        FOREIGN KEY (merged_into) REFERENCES public.manufacturers(id)
);

CREATE TABLE IF NOT EXISTS public.manufacturer_aliases (
    alias           text NOT NULL,
    manufacturer_id bigint NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT manufacturer_aliases_pkey PRIMARY KEY (alias),
    CONSTRAINT manufacturer_aliases_manufacturer_id_fkey
        FOREIGN KEY (manufacturer_id) REFERENCES public.manufacturers(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_manufacturer_aliases_manufacturer
    ON public.manufacturer_aliases USING btree (manufacturer_id);

-- ---------------------------------------------------------------------------
-- products: one row per scraped product, all markets
--
-- etl_loadtime = when the row FIRST entered the warehouse (never rewritten)
-- last_updated = when a SCRAPED field last actually changed
-- Both are naive timestamps written with Python local time while the DB runs
-- in Etc/UTC; the trigger below decides whether a writer's value survives.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.products (
    id                    uuid NOT NULL,
    group_id              uuid,
    name                  text,
    description           text,
    price                 integer,
    singular_price        text,
    in_stock              boolean,
    image                 text,
    link                  text,
    main_category         text,
    sub_category          text,
    confidence            double precision,
    market                text,
    name_embedding        vector(768) DEFAULT NULL::vector,
    etl_loadtime          timestamp NOT NULL DEFAULT now(),
    categorized_at        timestamp,
    last_updated          timestamp NOT NULL DEFAULT now(),
    -- feature extraction (extract_features.py)
    manufacturer_id       bigint,
    product_name          text,
    quantity_value        numeric(12, 3),
    quantity_unit         text,
    quantity_raw          text,
    is_fluid              boolean,
    metadata              jsonb,
    features_confidence   real,
    features_version      smallint,
    features_extracted_at timestamptz,
    -- deterministic grouping keys (grouping_keys.py)
    product_name_key      text,
    product_name_sorted   text,
    variant_key           text,
    grouping_keys_version smallint,
    variant               jsonb,
    CONSTRAINT products_pkey PRIMARY KEY (id),
    CONSTRAINT products_manufacturer_id_fkey
        FOREIGN KEY (manufacturer_id) REFERENCES public.manufacturers(id),
    CONSTRAINT products_quantity_unit_chk
        CHECK (quantity_unit IS NULL OR quantity_unit = ANY (ARRAY['g', 'kg', 'ml', 'l', 'pcs']))
);

-- ---------------------------------------------------------------------------
-- groups: one row per product identity, holds the representative metadata
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.groups (
    id                  uuid NOT NULL DEFAULT public.uuid_generate_v4(),
    name                text NOT NULL,
    main_category       text,
    sub_category        text,
    name_embedding      vector(768),
    clean_name          text,
    -- deterministic identity key (mirrors products)
    manufacturer_id     bigint,
    product_name        text,
    product_name_sorted text,
    quantity_value      numeric(12, 3),
    quantity_unit       text,
    is_fluid            boolean,
    variant_key         text,
    CONSTRAINT groups_pkey PRIMARY KEY (id),
    CONSTRAINT groups_manufacturer_id_fkey
        FOREIGN KEY (manufacturer_id) REFERENCES public.manufacturers(id)
);

-- ---------------------------------------------------------------------------
-- Timestamp semantics, enforced in the database
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.products_set_timestamps() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.etl_loadtime := COALESCE(NEW.etl_loadtime, now());
        NEW.last_updated := COALESCE(NEW.last_updated, NEW.etl_loadtime);
        RETURN NEW;
    END IF;

    -- First-seen time is immutable once the row exists.
    NEW.etl_loadtime := OLD.etl_loadtime;

    IF (NEW.name, NEW.description, NEW.price, NEW.singular_price,
        NEW.in_stock, NEW.image, NEW.link, NEW.market)
       IS DISTINCT FROM
       (OLD.name, OLD.description, OLD.price, OLD.singular_price,
        OLD.in_stock, OLD.image, OLD.link, OLD.market)
    THEN
        -- Keep the writer's timestamp; only invent one when the statement
        -- changed data without touching the column.
        IF NEW.last_updated IS NOT DISTINCT FROM OLD.last_updated THEN
            NEW.last_updated := localtimestamp;
        END IF;
    ELSE
        NEW.last_updated := OLD.last_updated;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS products_set_timestamps_trg ON public.products;
CREATE TRIGGER products_set_timestamps_trg
    BEFORE INSERT OR UPDATE ON public.products
    FOR EACH ROW
    EXECUTE FUNCTION public.products_set_timestamps();

-- ---------------------------------------------------------------------------
-- Indexes
-- ---------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_products_name
    ON public.products USING btree (name);

-- semantic search / embeddings fallback
CREATE INDEX IF NOT EXISTS idx_products_name_embedding
    ON public.products USING hnsw (name_embedding vector_cosine_ops)
    WITH (m = '16', ef_construction = '64');

-- legacy semantic grouping hot paths
CREATE INDEX IF NOT EXISTS idx_groups_category
    ON public.groups USING btree (main_category, sub_category)
    WHERE name_embedding IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_products_grouping
    ON public.products USING btree (main_category, sub_category)
    WHERE group_id IS NULL AND name_embedding IS NOT NULL;

-- feature extraction work queue
CREATE INDEX IF NOT EXISTS idx_products_features_pending
    ON public.products USING btree (id)
    WHERE features_extracted_at IS NULL;

-- deterministic grouping
CREATE INDEX IF NOT EXISTS idx_products_identity
    ON public.products USING btree (manufacturer_id, product_name, quantity_value,
                                    quantity_unit, is_fluid);

CREATE INDEX IF NOT EXISTS idx_products_group_key
    ON public.products USING btree (manufacturer_id, product_name_sorted, quantity_value,
                                    quantity_unit, is_fluid, variant_key);

CREATE INDEX IF NOT EXISTS idx_products_variant
    ON public.products USING gin (variant jsonb_path_ops);

-- /search: trigram matching over canonical product names + manufacturer names
CREATE INDEX IF NOT EXISTS idx_groups_product_name_trgm
    ON public.groups USING gin (product_name gin_trgm_ops);

CREATE INDEX IF NOT EXISTS idx_manufacturers_name_trgm
    ON public.manufacturers USING gin (canonical_name gin_trgm_ops);

-- NOTE: no unique index on the group natural key. Rule B (compatible variants)
-- means a group's stored key is its representative's, and two distinct groups in
-- the same block can legitimately share it (e.g. unbranded rows with no variant
-- info). Idempotency comes from the grouper rebuilding the table (TRUNCATE), not
-- from ON CONFLICT.

-- ---------------------------------------------------------------------------
-- API-facing view: one row per group, in-stock products only, cheapest first
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW public.grouped_products AS
SELECT g.id AS group_id,
       g.name AS group_name,
       g.main_category,
       g.sub_category,
       g.name_embedding,
       json_agg(json_build_object(
           'product_id', p.id,
           'name', p.name,
           'price', p.price,
           'market', p.market,
           'in_stock', p.in_stock,
           'image', p.image,
           'link', p.link,
           'singular_price', p.singular_price
       ) ORDER BY p.price) AS products
FROM public.groups g
JOIN public.products p ON p.group_id = g.id
WHERE p.in_stock = true
GROUP BY g.id;

ANALYZE public.products;
ANALYZE public.groups;
